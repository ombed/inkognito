/* Who uses what in the engine: for every top-level name of redact-engine.js, the engine/ file that declares
   it and the files that use it, read from eslint's scope analysis of the bundle (the files are concatenated
   in name order, so each line of the bundle belongs to one file). The engine's files share one scope and
   import nothing, so this table is the only place their dependencies are written down.

     node scripts/engine-map.js            # the table, as ARCHITECTURE.md holds it
     node scripts/engine-map.js --write    # rewrites that section of ARCHITECTURE.md

   tests/docs_t.js fails while the section differs from the code, so the map stays true. */
const fs = require("fs");
const path = require("path");
const { Linter } = require("eslint");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "engine");
const DOC = path.join(ROOT, "ARCHITECTURE.md");
const START = "<!-- engine-map:start (generated by scripts/engine-map.js; do not edit by hand) -->";
const END = "<!-- engine-map:end -->";

function files() {
  return fs.readdirSync(DIR).filter((f) => /^\d\d-.*\.js$/.test(f)).sort();
}

// for each file, the files whose names it uses (name: count), from the bundle's scope analysis
function map() {
  const list = files(), texts = list.map((f) => fs.readFileSync(path.join(DIR, f), "utf8"));
  const starts = [];
  let line = 1;
  for (const t of texts) { starts.push(line); line += t.split("\n").length - 1; }
  const fileAt = (ln) => { let k = 0; while (k + 1 < starts.length && starts[k + 1] <= ln) k++; return list[k]; };
  const linter = new Linter({ configType: "flat" });
  const msgs = linter.verify(texts.join(""), [{ languageOptions: { ecmaVersion: "latest", sourceType: "module" } }]);
  const fatal = msgs.find((m) => m.fatal);
  if (fatal) throw new Error(`the engine does not parse: ${fatal.message}, line ${fatal.line}`);
  const scope = linter.getSourceCode().scopeManager.globalScope.childScopes.find((s) => s.type === "module");
  const uses = new Map(list.map((f) => [f, new Map()])); // user -> owner -> Set(names)
  for (const v of scope.variables) {
    const def = v.defs[0];
    if (!def) continue;
    const owner = fileAt(def.name.loc.start.line);
    for (const r of v.references) {
      const user = fileAt(r.identifier.loc.start.line);
      if (user === owner) continue;
      const by = uses.get(user);
      if (!by.has(owner)) by.set(owner, new Set());
      by.get(owner).add(v.name);
    }
  }
  return { list, uses };
}

// the files that reach each other in a cycle (strongly connected components of more than one file)
function cycles({ list, uses }) {
  const idx = new Map(), low = new Map(), on = new Set(), stack = [], out = [];
  let n = 0;
  const visit = (f) => {
    idx.set(f, n); low.set(f, n); n++; stack.push(f); on.add(f);
    for (const g of uses.get(f).keys()) {
      if (!idx.has(g)) { visit(g); low.set(f, Math.min(low.get(f), low.get(g))); }
      else if (on.has(g)) low.set(f, Math.min(low.get(f), idx.get(g)));
    }
    if (low.get(f) === idx.get(f)) {
      const c = [];
      for (;;) { const g = stack.pop(); on.delete(g); c.push(g); if (g === f) break; }
      if (c.length > 1) out.push(c.sort());
    }
  };
  for (const f of list) if (!idx.has(f)) visit(f);
  return out;
}

function table(m) {
  const rows = ["| file | uses names from | used by |", "|---|---|---|"];
  for (const f of m.list) {
    const from = [...m.uses.get(f)].sort((a, b) => b[1].size - a[1].size || (a[0] < b[0] ? -1 : 1))
      .map(([g, names]) => `${g.replace(/\.js$/, "")} (${names.size})`).join(", ") || "none";
    const by = m.list.filter((g) => m.uses.get(g).has(f)).map((g) => g.replace(/\.js$/, "")).join(", ") || "none";
    rows.push(`| \`${f}\` | ${from} | ${by} |`);
  }
  const cyc = cycles(m);
  const note = cyc.length
    ? cyc.map((c) => `These ${c.length} files reach one another in a cycle: ${c.map((f) => "`" + f.replace(/\.js$/, "") + "`").join(", ")}.`).join(" ")
    : "No two files reach one another in a cycle.";
  return [START, "", rows.join("\n"), "", note, "", END].join("\n");
}

module.exports = { map, cycles, table, START, END };

if (require.main === module) {
  const t = table(map());
  if (process.argv.includes("--write")) {
    const doc = fs.readFileSync(DOC, "utf8");
    const a = doc.indexOf(START), b = doc.indexOf(END);
    if (a < 0 || b < 0) throw new Error("ARCHITECTURE.md has no engine-map section");
    fs.writeFileSync(DOC, doc.slice(0, a) + t + doc.slice(b + END.length));
    console.log("wrote the engine map into ARCHITECTURE.md");
  } else console.log(t);
}
